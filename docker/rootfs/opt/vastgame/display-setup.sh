#!/bin/bash
# EDID и xorg.conf как на KVM (wolf-setup.sh, HARDENING #1): виртуальный монитор (единственный тайминг
# 1920x1200@60 CVT-RB), проверки режимов драйвера отключены, базовый режим $1; остальные режимы wolf-res создаёт
# на лету под клиента Moonlight (global_prep_cmd Sunshine).
set -u
RES=${1:-1920x1200}
echo "$RES" > /etc/wolf-res.conf && chmod 644 /etc/wolf-res.conf
touch /var/log/wolf-res.log && chown user: /var/log/wolf-res.log
python3 - > /etc/X11/wolf.edid <<'PY'
import sys
e = bytes([
 0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0x00,
 0x5D,0x86, 0x01,0x00, 0x01,0x00,0x00,0x00, 0x01,0x21, 0x01,0x03,
 0x80, 0x34,0x20, 0x78, 0x0A,
 0xEE,0x91,0xA3,0x54,0x4C,0x99,0x26,0x0F,0x50,0x54,
 0x00,0x00,0x00,
 0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,0x01,
 0x28,0x3C,0x80,0xA0,0x70,0xB0,0x23,0x40,0x30,0x20,0x36,0x00,0x06,0x44,0x21,0x00,0x00,0x1A,
 0x00,0x00,0x00,0xFD,0x00,0x32,0x4B,0x1E,0x5F,0x10,0x00,0x0A,0x20,0x20,0x20,0x20,0x20,0x20,
 0x00,0x00,0x00,0xFC,0x00,0x57,0x4F,0x4C,0x46,0x0A,0x20,0x20,0x20,0x20,0x20,0x20,0x20,0x20,
 0x00,0x00,0x00,0x10,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
 0x00,
])
sys.stdout.buffer.write(e + bytes([(-sum(e)) & 0xFF]))
PY
IFS=:. read -r _ b1 b2 b3 <<< "$(nvidia-smi --query-gpu=pci.bus_id --format=csv,noheader 2>/dev/null | head -1)"
[ -n "${b3:-}" ] || { echo "экран: не узнать шину видеокарты"; exit 1; }
cat > /etc/X11/xorg.conf <<XORG
Section "ServerFlags"
    Option "AutoAddDevices" "false"
EndSection
Section "Device"
    Identifier "wolfGPU"
    Driver     "nvidia"
    BusID      "PCI:$((16#$b1)):$((16#$b2)):$((16#$b3))"
    Option     "AllowEmptyInitialConfiguration" "true"
    Option     "ConnectedMonitor" "DFP-0"
    Option     "CustomEDID" "DFP-0:/etc/X11/wolf.edid"
    Option     "ModeValidation" "DFP-0: NoMaxPClkCheck, NoEdidMaxPClkCheck, NoHorizSyncCheck, NoVertRefreshCheck, NoDualLinkDVICheck, AllowNonEdidModes"
    Option     "HardDPMS" "false"
EndSection
Section "Screen"
    Identifier   "wolfScreen"
    Device       "wolfGPU"
    DefaultDepth 24
    Option       "MetaModes" "DFP-0: $RES +0+0"
    SubSection "Display"
        Depth   24
        Modes   "$RES"
        Virtual 3840 3840
    EndSubSection
EndSection
XORG
echo "экран: EDID и xorg.conf, базовый режим $RES"
