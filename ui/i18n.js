const LANGUAGES = { ru: "Русский", en: "English", es: "Español" };
let LANG = "en";

// Язык системы: первый из предпочтительных, который у нас есть; иначе английский
function detectLanguage() {
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (I18N[code]) return code;
  }
  return "en";
}

let GAME_NAMES = {};   // {appid: название игры} — приходят из Python, нужны для имён сохранений

// Перевод по ключу с подстановками: t("app.updated", {time: "12:00"}).
// Список в подстановке — это имена архивов: показываем их понятными словами через запятую.
let PLATFORM = "";     // sys.platform из Python (Api.settings): "darwin", "win32" — для вариантов текста «ключ@win»

function t(key, params = {}) {
  if (PLATFORM === "win32" && I18N.en[key + "@win"]) key += "@win";       // на Windows — свой вариант, если есть
  const text = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
  return text.replace(/\{(\w+)\}/g, (m, name) => {
    if (!(name in params)) return m;
    const v = params[name];
    return Array.isArray(v) ? v.map((n) => archiveName(n)).join(", ") : v;
  });
}

// Статичные тексты страницы: <span data-i18n="btn.play">, title — data-i18n-title
function applyStatic() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
}

// Понятное имя архива wolf: identity → «сетевая личность», pfx--1086940 → «сохранения Baldur's Gate 3»
function archiveName(name, gameNames = GAME_NAMES) {
  if (I18N.en["archive." + name]) return t("archive." + name);
  const mod = /^mod--\d+--(.+)$/.exec(name);                   // [v5.0] моды: mod--НОМЕР--Название
  if (mod) return t("archive.mod", { name: mod[1] });
  const gs = /^gsave--\d+--(.+)$/.exec(name);                 // [v5.7] данные игры: gsave--НОМЕР--Название
  if (gs) return t("archive.gsave", { name: gs[1] });
  const m = /^(pfx|game|sgame|prog)--(.+)$/.exec(name);
  if (!m) return name;
  const shown = m[1] === "pfx" ? gameNames[m[2]] || "appid " + m[2] : m[2];
  return t("archive." + m[1], { name: shown });
}
